const OUTPUT_NOTES = Object.freeze({
  cover: '封面将方向转化为单一主视觉、横向构图和缩略图可辨识的标题层级。',
  article: '文章排版将方向转化为标题、章节、引用、数据和图片说明的层级，不把全文做成重复卡片。',
  social: '分页图文将方向转化为整组卡片的一致视觉语言，并让每页版式服务该页信息结构。',
});

export function visualDirectionReference(kind = 'article') {
  const outputNote = OUTPUT_NOTES[kind] || OUTPUT_NOTES.article;
  if (kind !== 'social') {
    const options = DIRECTIONS.map(([name, description]) => `- ${name}：${description}`).join('\n');
    return `## 候选视觉方向参考\n${options}\n\n${outputNote}\n根据当前内容的主题、情绪、受众和信息结构选择最合适的一种，允许融合相邻方向，但须明确主方向并落实到配色、字体、构图和装饰。候选是灵感参考，不是固定模板；不要只改强调色就复用同一套设计。暖纸感不是默认选项：若主题没有明确理由，优先考虑冷色、深色、高对比、明亮几何或极简方向。若输入提供近期作品的视觉方向或主背景色，避免与最近作品重复；未提供历史时也应主动在明暗、冷暖和主色上作出清晰选择。始终满足现有对比度、画布、内容保真和组件契约。`;
  }
  const options = ELEMENT_OPTIONS.map(([name, description]) => `- ${name}：${description}`).join('\n');
  return `## 内容驱动的视觉元素参考\n${options}\n\n${outputNote}\n先从具体内容提炼主题对象、叙事方式、读者感受和最值得看见的证据/结果，再逐项选择视觉元素并组合成主视觉方向。工具、事件、自定义等内容类型只是流程元数据，不是风格选择器；同一类型可以得到不同组合，不同类型也可以共享部分元素。不要把数据/技术固定映射成冷白，把工具固定映射成明亮几何，或把事件固定映射成档案纸感。避免只换强调色而复用同一套结构；历史风格只有在输入明确提供时才可用于去重。始终满足对比度、画布、内容保真和组件契约。`;
}
